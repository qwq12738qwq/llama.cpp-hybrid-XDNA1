#!/usr/bin/env python3
"""
Phase 20D: Multi-column kernel generation for missing C2/C3/C4 shapes.

Phoenix XDNA1 exposes 4 AIE columns:
  npu1_1col  -> 1 column (C1)
  npu1_2col  -> 2 columns (C2)
  npu1_3col  -> 3 columns (C3)
  npu1       -> full 4-column (C4)

This script generates MLIR-AIE designs for missing multi-column kernels
covering P0 Qwen3.5-0.8B production shapes.

Usage:
    python3 gen_multicolumn_kernels.py [--dry-run] [--output-dir DIR]

Output:
    MLIR-AIE source files for each missing shape, plus compilation commands.
"""

import os
import sys
import argparse
from pathlib import Path

# P0 shapes: M512/M448, K=1024, N=3072/4096/6144
# These are the Qwen3.5-0.8B PP production GEMM shapes
P0_SHAPES = [
    # (M, K, N, description)
    (512, 1024, 3072, "Q-proj/O-proj"),
    (512, 1024, 4096, "FFN up/gate"),
    (512, 1024, 6144, "FFN down"),
    (448, 1024, 4096, "FFN up/gate (short ctx)"),
    (448, 1024, 6144, "FFN down (short ctx)"),
]

# Column configurations
COLUMNS = [1, 2, 3, 4]

# Tile sizes (consistent with Phase 18/20 kernels)
TM = 64  # M tile
TK = 64  # K tile (for I8) or 32 (for Q8_0)
TN = 64  # N tile

# MLIR-AIE device names
DEVICE_MAP = {
    1: "npu1_1col",
    2: "npu1_2col",
    3: "npu1_3col",
    4: "npu1",  # full device = 4 columns
}


def generate_mlir_design(M, K, N, n_cols, Tk=64):
    """Generate MLIR-AIE design for a given shape and column count."""
    device = DEVICE_MAP[n_cols]
    # N per column
    N_per_col = N // n_cols
    if N % n_cols != 0:
        return None  # N must be divisible by n_cols

    # Number of N-tiles per column
    n_tiles_per_col = (N_per_col + TN - 1) // TN
    # Number of M-tiles
    m_tiles = (M + TM - 1) // TM
    # Number of K-tiles
    k_tiles = (K + Tk - 1) // Tk

    mlir = f"""// Auto-generated by Phase 20D multi-column kernel generator
// Shape: M={M}, K={K}, N={N}, C={n_cols}
// Device: {device}
// N per column: {N_per_col}
// Tiles: m={m_tiles}, k={k_tiles}, n_per_col={n_tiles_per_col}

module {{
    aie.device({device}) {{
        // Compute tiles (one per column)
"""
    for col in range(n_cols):
        mlir += f"""        %tile_compute_{col} = aie.tile({col}, 2)
        %tile_mem_{col} = aie.tile({col}, 1)
"""
    mlir += f"""
        // ObjectFIFOs for input/output distribution
"""
    for col in range(n_cols):
        mlir += f"""        aie.objectfifo @of_in_{col}(%tile_mem_{col}, {{%tile_compute_{col}}}, 2 : i32) = !aie.objectfifo<memref<{Tk}x{TN}xi8>>
        aie.objectfifo @of_weight_{col}(%tile_mem_{col}, {{%tile_compute_{col}}}, 2 : i32) = !aie.objectfifo<memref<{Tk}x{TN}xi8>>
        aie.objectfifo @of_out_{col}(%tile_compute_{col}, {{%tile_mem_{col}}}, 2 : i32) = !aie.objectfifo<memref<{TM}x{TN}xi32>>
"""
    mlir += f"""
        // Core programs
"""
    for col in range(n_cols):
        mlir += f"""        %core_{col} = aie.core(%tile_compute_{col}) {{
            scf.for {{}} {{}} to ({k_tiles}) {{
                // TODO: implement vectorized matmul_i8_i32
                // This is a placeholder for the actual compute kernel
            }}
            aie.end
        }} : () -> ()
"""
    mlir += f"""
        // DMA flows
"""
    for col in range(n_cols):
        mlir += f"""        aie.flow(%tile_mem_{col}, DMA : 0, %tile_compute_{col}, DMA : 0)
        aie.flow(%tile_mem_{col}, DMA : 1, %tile_compute_{col}, DMA : 1)
        aie.flow(%tile_compute_{col}, DMA : 0, %tile_mem_{col}, DMA : 0)
"""
    mlir += """    }
}
"""
    return mlir


def check_existing_kernels(cache_dir, M, K, n_cols):
    """Check which kernels already exist in the cache."""
    existing = []
    missing = []

    for N, desc in [(3072, "Q-proj"), (4096, "FFN-up"), (6144, "FFN-down")]:
        # Check various naming conventions
        paths = [
            f"M{M}_K{K}_N{N}_C{n_cols}_Tm{TM}_Tk{TK}_Tn{TN}",
            f"M{M}_K{K}_N{N}_C{n_cols}",
        ]
        found = False
        for p in paths:
            xclbin = os.path.join(cache_dir, p, "design.xclbin")
            insts = os.path.join(cache_dir, p, "design.insts.bin")
            if os.path.exists(xclbin) and os.path.exists(insts):
                existing.append((M, K, N, n_cols, p))
                found = True
                break
        if not found:
            missing.append((M, K, N, n_cols, desc))

    return existing, missing


def main():
    parser = argparse.ArgumentParser(description="Generate multi-column kernels for Phase 20D")
    parser.add_argument("--dry-run", action="store_true", help="Print generation plan without writing files")
    parser.add_argument("--output-dir", default="/workspace/llama.cpp/experiments/phase20d/kernels",
                        help="Output directory for MLIR designs")
    parser.add_argument("--cache-dir", default="/workspace/llama.cpp/experiments/npu-int8-gemm/kernel_cache",
                        help="Existing kernel cache directory")
    args = parser.parse_args()

    os.makedirs(args.output_dir, exist_ok=True)

    print("=" * 80)
    print("Phase 20D: Multi-column Kernel Generation")
    print("=" * 80)
    print()

    total_existing = 0
    total_missing = 0
    total_generated = 0

    for M, K, N, desc in P0_SHAPES:
        print(f"\n--- Shape: M={M} K={K} N={N} ({desc}) ---")

        for n_cols in COLUMNS:
            if N % n_cols != 0:
                print(f"  C{n_cols}: SKIPPED (N={N} not divisible by {n_cols})")
                continue

            existing, missing = check_existing_kernels(args.cache_dir, M, K, n_cols)
            n_exist = len([e for e in existing if e[2] == N])
            n_miss = len([m for m in missing if m[2] == N])

            if n_exist > 0:
                print(f"  C{n_cols}: EXISTS ({n_exist} kernels)")
                total_existing += n_exist
            else:
                print(f"  C{n_cols}: MISSING - generating MLIR design")
                total_missing += 1

                if not args.dry_run:
                    mlir = generate_mlir_design(M, K, N, n_cols, Tk=TK)
                    if mlir:
                        kernel_dir = os.path.join(args.output_dir,
                                                  f"M{M}_K{K}_N{N}_C{n_cols}_Tm{TM}_Tk{TK}_Tn{TN}")
                        os.makedirs(kernel_dir, exist_ok=True)
                        with open(os.path.join(kernel_dir, "design.mlir"), "w") as f:
                            f.write(mlir)
                        total_generated += 1
                        print(f"    -> {kernel_dir}/design.mlir")
                    else:
                        print(f"    -> FAILED (N not divisible by C{n_cols})")

    print()
    print("=" * 80)
    print("Summary")
    print("=" * 80)
    print(f"  Existing kernels: {total_existing}")
    print(f"  Missing kernels:  {total_missing}")
    print(f"  Generated:        {total_generated}")
    print()

    if total_missing > 0 and args.dry_run:
        print("Run without --dry-run to generate MLIR designs.")
        print()
        print("To compile kernels, use:")
        print("  cd <kernel_dir> && aiecc.py design.mlir -o design.xclbin")

    # Output compilation matrix
    print()
    print("Compilation matrix (shapes that need xclbin):")
    print(f"{'M':>6} {'K':>6} {'N':>6} {'C':>3} {'Status':>10}")
    print("-" * 40)
    for M, K, N, desc in P0_SHAPES:
        for n_cols in COLUMNS:
            if N % n_cols != 0:
                continue
            existing, missing = check_existing_kernels(args.cache_dir, M, K, n_cols)
            n_exist = len([e for e in existing if e[2] == N])
            status = "OK" if n_exist > 0 else "MISSING"
            print(f"{M:>6} {K:>6} {N:>6} {n_cols:>3} {status:>10}")


if __name__ == "__main__":
    main()
